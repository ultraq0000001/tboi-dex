/**
 * Generates src/data/generatedTrinketIcons.ts — a static require() registry of
 * every trinket icon under assets/media/Trinkets, keyed by the id-based icon
 * filename (trinket_<id>_icon.png), plus the resolver that maps a trinket in
 * trinkets_rebirth.json to its icon via that trinket's `icon` field.
 *
 * Metro requires `require()` calls to reference static paths, so this script
 * is run before bundling whenever the trinket dataset or icon assets change:
 *
 *   node scripts/generate-trinket-icons.mjs
 *
 * Both the registry and the resolver live here so they can never drift apart.
 */
import { readFileSync, readdirSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const dataDir = join(root, 'src', 'data');
const iconsDir = join(root, 'assets', 'media', 'Trinkets');

const trinkets = JSON.parse(readFileSync(join(dataDir, 'trinkets_rebirth.json'), 'utf8'));

// Only id-based icon files that correspond to a trinket in the dataset.
const idPattern = /^trinket_(\d+)_icon\.png$/;
const allFiles = readdirSync(iconsDir).filter((f) => f.toLowerCase().endsWith('.png'));
const trinketIds = new Set(trinkets.map((i) => String(i.id)));
const registryFiles = allFiles.filter((f) => idPattern.test(f) && trinketIds.has(idPattern.exec(f)[1]));

/**
 * Resolve the icon filename for a trinket, or null if no icon exists.
 * Uses the trinket's id-based `icon` field, and only returns it when the file
 * is actually part of the registry (so a missing file degrades to null).
 */
function iconFilenameForTrinket(trinket) {
  if (trinket && typeof trinket.icon === 'string' && registryFiles.includes(trinket.icon)) {
    return trinket.icon;
  }
  return null;
}

const quote = (s) => JSON.stringify(s);

const requireLines = [...registryFiles]
  .sort()
  .map((f) => `  ${quote(f)}: require(${quote('../../assets/media/Trinkets/' + f)}),`)
  .join('\n');

const output = `/**
 * AUTO-GENERATED by scripts/generate-trinket-icons.mjs — DO NOT EDIT BY HAND.
 * Regenerate with: node scripts/generate-trinket-icons.mjs
 *
 * Static require() registry of trinket icons under assets/media/Trinkets,
 * keyed by the id-based icon filename (trinket_<id>_icon.png), plus the
 * resolver that maps a trinket from trinkets_rebirth.json to its icon via the
 * trinket's \`icon\` field. Generated only for trinkets in trinkets_rebirth.json
 * so the bundle stays small.
 */
import { ImageSourcePropType } from 'react-native';

/** Map of icon filename -> bundled module, also used as the known-file set. */
export const trinketIcons: Partial<Record<string, ImageSourcePropType>> = {
${requireLines}
};

const KNOWN = new Set(Object.keys(trinketIcons));

/** Resolve the icon filename for a trinket (or null if no icon exists). */
export function iconFilenameForTrinket(trinket: { icon?: string }): string | null {
  if (trinket && typeof trinket.icon === 'string' && KNOWN.has(trinket.icon)) return trinket.icon;
  return null;
}
`;

writeFileSync(join(dataDir, 'generatedTrinketIcons.ts'), output);

console.log(`Wrote generatedTrinketIcons.ts with ${registryFiles.length} icons (${trinkets.length} trinkets).`);
const unmatched = trinkets.filter((i) => !iconFilenameForTrinket(i));
if (unmatched.length) {
  console.log(`WARNING: ${unmatched.length} trinket(s) have no icon:`, unmatched.map((i) => i.name));
}